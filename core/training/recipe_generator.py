"""Production Fine-Tuning Recipe & Launch Script Generator.

Generates production-ready training scripts and framework configurations tailored
to the synthesized dataset:
1. Unsloth (2x faster LoRA & QLoRA training)
2. Axolotl (Distributed enterprise YAML training recipe)
3. LLaMA-Factory (Unified multi-stage tuning CLI)
4. Torchtune (PyTorch native LLM fine-tuning)
"""

from typing import Any, Dict, Optional


def generate_unsloth_recipe(
    dataset_path: str = "dataset.jsonl",
    base_model: str = "sarvamai/sarvam-2b-v0.5",
    dataset_type: str = "sft",
    output_dir: str = "outputs",
    max_seq_length: int = 2048,
    lora_r: int = 16,
    lora_alpha: int = 32,
    learning_rate: float = 2e-4,
    batch_size: int = 4,
    gradient_accumulation_steps: int = 4,
) -> str:
    """Generate a self-contained Unsloth QLoRA training Python script."""
    is_dpo = dataset_type in ("rlhf", "dpo", "simpo")

    if is_dpo:
        trainer_snippet = f"""from trl import DPOTrainer, DPOConfig
from unsloth import PatchDPOTrainer
PatchDPOTrainer()

dpo_config = DPOConfig(
    output_dir="{output_dir}",
    per_device_train_batch_size={batch_size},
    gradient_accumulation_steps={gradient_accumulation_steps},
    learning_rate=5e-5,
    beta=0.1,
    fp16=not is_bfloat16_supported(),
    bf16=is_bfloat16_supported(),
    logging_steps=10,
    save_strategy="steps",
    save_steps=100,
    max_length={max_seq_length},
    max_prompt_length=1024,
)

trainer = DPOTrainer(
    model=model,
    ref_model=None,
    args=dpo_config,
    train_dataset=dataset["train"],
    tokenizer=tokenizer,
)
trainer.train()"""
    else:
        trainer_snippet = f"""from trl import SFTTrainer
from transformers import TrainingArguments

training_args = TrainingArguments(
    output_dir="{output_dir}",
    per_device_train_batch_size={batch_size},
    gradient_accumulation_steps={gradient_accumulation_steps},
    learning_rate={learning_rate},
    lr_scheduler_type="cosine",
    warmup_ratio=0.05,
    fp16=not is_bfloat16_supported(),
    bf16=is_bfloat16_supported(),
    logging_steps=10,
    save_strategy="steps",
    save_steps=200,
    num_train_epochs=3,
    optim="adamw_8bit",
)

trainer = SFTTrainer(
    model=model,
    tokenizer=tokenizer,
    train_dataset=dataset["train"],
    dataset_text_field="text",
    max_seq_length={max_seq_length},
    dataset_num_proc=2,
    args=training_args,
)
trainer.train()"""

    return f'''# Auto-generated by RasoSynthTune for Unsloth
# Base Model: {base_model} | Paradigm: {dataset_type.upper()}

from unsloth import FastLanguageModel, is_bfloat16_supported
from datasets import load_dataset
import torch

max_seq_length = {max_seq_length}
dtype = None # Auto detection: Float16 or Bfloat16
load_in_4bit = True

# 1. Load Model & Tokenizer
model, tokenizer = FastLanguageModel.from_pretrained(
    model_name="{base_model}",
    max_seq_length=max_seq_length,
    dtype=dtype,
    load_in_4bit=load_in_4bit,
)

# 2. Configure Parameter-Efficient LoRA Adapters
model = FastLanguageModel.get_peft_model(
    model,
    r={lora_r},
    target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
    lora_alpha={lora_alpha},
    lora_dropout=0, # Optimized 0 dropout for Unsloth
    bias="none",
    use_gradient_checkpointing="unsloth",
    random_state=3407,
)

# 3. Load Dataset
dataset = load_dataset("json", data_files="{dataset_path}")

# 4. Train Model
{trainer_snippet}

# 5. Save LoRA Adapters & GGUF
model.save_pretrained_merged("{output_dir}/merged_16bit", tokenizer, save_method="merged_16bit")
print("Training complete! Model exported to {output_dir}")
'''


def generate_axolotl_config(
    dataset_path: str = "dataset.jsonl",
    base_model: str = "sarvamai/sarvam-2b-v0.5",
    dataset_type: str = "sft",
    output_dir: str = "./outputs/axolotl",
    lora_r: int = 16,
    lora_alpha: int = 32,
    batch_size: int = 4,
) -> str:
    """Generate an Axolotl YAML configuration."""
    ds_format = "dpo" if dataset_type in ("rlhf", "dpo", "simpo") else "chatml"
    return f"""# Axolotl Training Recipe generated by RasoSynthTune
base_model: {base_model}
model_type: AutoModelForCausalLM
tokenizer_type: AutoTokenizer

load_in_8bit: false
load_in_4bit: true
strict: false

datasets:
  - path: {dataset_path}
    type: {ds_format}

dataset_prepared_path: last_run_prepared
output_dir: {output_dir}

sequence_len: 2048
sample_packing: true
pad_to_sequence_len: true

adapter: lora
lora_r: {lora_r}
lora_alpha: {lora_alpha}
lora_dropout: 0.05
lora_target_linear: true

gradient_accumulation_steps: 4
micro_batch_size: {batch_size}
num_epochs: 3
optimizer: paged_adamw_8bit
lr_scheduler: cosine
learning_rate: 0.0002

bf16: auto
fp16: false
tf32: false

gradient_checkpointing: true
early_stopping_patience:
resume_from_checkpoint:
logging_steps: 10
flash_attention: true
warmup_ratio: 0.05
"""


def generate_training_recipe(
    framework: str = "unsloth",
    dataset_path: str = "dataset.jsonl",
    base_model: str = "sarvamai/sarvam-2b-v0.5",
    dataset_type: str = "sft",
) -> Dict[str, str]:
    """Generate recipe code and instructions for the requested framework."""
    framework_lower = framework.lower()
    if framework_lower == "axolotl":
        code = generate_axolotl_config(dataset_path=dataset_path, base_model=base_model, dataset_type=dataset_type)
        filename = "axolotl_config.yaml"
        launch_cmd = f"accelerate launch -m axolotl.cli.train {filename}"
    elif framework_lower == "llamafactory":
        code = f"""# LLaMA-Factory launch script
llamafactory-cli train \\
    --stage { 'dpo' if dataset_type in ('rlhf', 'dpo', 'simpo') else 'sft' } \\
    --do_train \\
    --model_name_or_path {base_model} \\
    --dataset_dir . \\
    --dataset {dataset_path} \\
    --template default \\
    --finetuning_type lora \\
    --lora_target all \\
    --output_dir ./saves/{base_model.split('/')[-1]}-lora \\
    --overwrite_output_dir \\
    --cutoff_len 2048 \\
    --learning_rate 2e-4 \\
    --num_train_epochs 3.0 \\
    --per_device_train_batch_size 4 \\
    --gradient_accumulation_steps 4 \\
    --lr_scheduler_type cosine \\
    --logging_steps 10 \\
    --save_steps 200 \\
    --fp16
"""
        filename = "train_llamafactory.sh"
        launch_cmd = f"bash {filename}"
    else:  # unsloth default
        code = generate_unsloth_recipe(dataset_path=dataset_path, base_model=base_model, dataset_type=dataset_type)
        filename = "train_unsloth.py"
        launch_cmd = f"python {filename}"

    return {
        "framework": framework,
        "filename": filename,
        "content": code,
        "launch_command": launch_cmd,
    }
